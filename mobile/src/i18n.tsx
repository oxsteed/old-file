function interpolate(template: string, params?: TranslationParams) {
  if (!params) return template;
  return Object.entries(params).reduce(
    (message, [key, value]) => message.replaceAll(`{{${key}}}`, String(value)),
    template
  );
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function MobileI18nProvider({ children }: PropsWithChildren) {
  const language = useAppPreferencesStore((state) => state.language);
  const setLanguage = useAppPreferencesStore((state) => state.setLanguage);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, params) => {
        const template =
          translations[language][key] ??
          translations.en[key] ??
          key;
        return interpolate(template, params);
      },
      formatCurrency: (value) =>
        new Intl.NumberFormat(localeMap[language] || "en-US", {
          style: "currency",
          currency: "USD"
        }).format(value),
      formatDate: (value) =>
        new Intl.DateTimeFormat(localeMap[language] || "en-US", {
          month: "short",
          day: "numeric",
          year: "numeric"
        }).format(typeof value === "string" ? new Date(value) : value)
    }),
    [language, setLanguage]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside MobileI18nProvider.");
  }
  return context;
}

