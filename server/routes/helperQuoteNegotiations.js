'use strict';
const router=require('express').Router();
const {authenticate}=require('../middleware/auth');
const {rejectImpersonated}=require('../middleware/rejectImpersonated');
const {generalLimiter}=require('../middleware/rateLimiter');
const service=require('../services/helperQuoteNegotiation');
router.use(authenticate,generalLimiter,(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
const handle=fn=>async(req,res,next)=>{try{await fn(req,res);}catch(error){next(error);}};
router.get('/materials',handle(async(req,res)=>res.json({templates:await service.templates(req.user.id)})));
router.post('/materials',rejectImpersonated,handle(async(req,res)=>res.status(201).json({template:await service.templateCreate(req.user.id,req.body)})));
router.put('/materials/:id',rejectImpersonated,handle(async(req,res)=>res.json({template:await service.templateUpdate(req.user.id,req.params.id,req.body)})));
router.delete('/materials/:id',rejectImpersonated,handle(async(req,res)=>{await service.templateDelete(req.user.id,req.params.id);res.sendStatus(204);}));
router.get('/jobs/:jobId',handle(async(req,res)=>res.json(await service.list(req.params.jobId,req.user.id))));
router.post('/jobs/:jobId',rejectImpersonated,handle(async(req,res)=>res.status(201).json({quote:await service.create(req.params.jobId,req.user.id,req.body)})));
router.post('/:id/revise',rejectImpersonated,handle(async(req,res)=>res.status(201).json({quote:await service.revise(req.params.id,req.user.id,req.body)})));
router.post('/:id/respond',rejectImpersonated,handle(async(req,res)=>res.json({quote:await service.respond(req.params.id,req.user.id,req.body)})));
router.post('/:id/counter',rejectImpersonated,handle(async(req,res)=>res.status(201).json({counter:await service.counter(req.params.id,req.user.id,req.body)})));
router.post('/counters/:id/respond',rejectImpersonated,handle(async(req,res)=>res.json(await service.counterRespond(req.params.id,req.user.id,req.body))));
module.exports=router;
