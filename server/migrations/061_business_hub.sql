-- Migration 061: Business Hub
-- Transforms the businesses table into a full operating layer:
-- per-business invoices, tax estimates, revenue goals, and expense attribution.

-- ── 1. Extend businesses table ───────────────────────────────────────────────
ALTER TABLE businesses
  ADD COLUMN IF NOT EXISTS description    VARCHAR(500),
  ADD COLUMN IF NOT EXISTS website        VARCHAR(255),
  ADD COLUMN IF NOT EXISTS phone          VARCHAR(30),
  ADD COLUMN IF NOT EXISTS logo_url       VARCHAR(500),
  -- Effective tax rate the user wants to reserve (default 25% for self-employed)
  ADD COLUMN IF NOT EXISTS tax_rate       NUMERIC(5,2) NOT NULL DEFAULT 25.00,
  -- Invoice counter — auto-incremented for human-readable invoice numbers
  ADD COLUMN IF NOT EXISTS invoice_seq    INT          NOT NULL DEFAULT 0;

-- ── 2. Tag expenses with a business ──────────────────────────────────────────
ALTER TABLE expenses
  ADD COLUMN IF NOT EXISTS business_id INT REFERENCES businesses(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_expenses_business_id
  ON expenses (business_id)
  WHERE business_id IS NOT NULL;

-- ── 3. Business invoices ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS business_invoices (
  id             BIGSERIAL PRIMARY KEY,
  user_id        UUID        NOT NULL REFERENCES users(id)       ON DELETE CASCADE,
  business_id    INT         NOT NULL REFERENCES businesses(id)  ON DELETE CASCADE,
  -- Human-readable number e.g. "INV-2026-0042"
  invoice_number VARCHAR(40) NOT NULL,
  -- Who is being billed
  client_name    VARCHAR(120) NOT NULL,
  client_email   VARCHAR(255),
  client_company VARCHAR(120),
  -- Lifecycle
  status         VARCHAR(20) NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft','sent','paid','overdue','cancelled','partial')),
  issue_date     DATE        NOT NULL DEFAULT CURRENT_DATE,
  due_date       DATE,
  -- Amounts — always stored in dollars
  subtotal       NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Tax percentage (0 = no sales tax on invoice; separate from income tax reserve)
  invoice_tax_rate NUMERIC(5,2) DEFAULT 0,
  tax_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
  total          NUMERIC(12,2) NOT NULL DEFAULT 0,
  amount_paid    NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Line items: [{description, quantity, unit_price, amount}]
  line_items     JSONB         NOT NULL DEFAULT '[]',
  -- Optional
  notes          VARCHAR(1000),
  -- Linked to an OxSteed job (optional)
  job_id         UUID REFERENCES jobs(id) ON DELETE SET NULL,
  -- Timestamps
  sent_at        TIMESTAMPTZ,
  paid_at        TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_business_invoices_user     ON business_invoices(user_id);
CREATE INDEX IF NOT EXISTS idx_business_invoices_business ON business_invoices(business_id);
CREATE INDEX IF NOT EXISTS idx_business_invoices_status   ON business_invoices(status);
CREATE INDEX IF NOT EXISTS idx_business_invoices_due_date ON business_invoices(due_date)
  WHERE due_date IS NOT NULL AND status NOT IN ('paid','cancelled');

-- ── 4. Quarterly estimated tax obligations ─────────────────────────────────
-- Auto-generated by the tax-estimate engine each time the user refreshes.
-- Stored so the Pulse can include upcoming tax payments as obligations.
CREATE TABLE IF NOT EXISTS business_tax_estimates (
  id                    BIGSERIAL PRIMARY KEY,
  user_id               UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- NULL business_id = combined across all businesses
  business_id           INT REFERENCES businesses(id) ON DELETE CASCADE,
  tax_year              SMALLINT    NOT NULL,
  quarter               SMALLINT    NOT NULL CHECK (quarter BETWEEN 1 AND 4),
  -- Estimated net income for this quarter (revenue - deductible expenses)
  estimated_net_income  NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Tax rate used when this estimate was calculated
  tax_rate_used         NUMERIC(5,2)  NOT NULL DEFAULT 25.00,
  -- Tax owed this quarter
  estimated_tax         NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- IRS quarterly payment deadline
  due_date              DATE         NOT NULL,
  status                VARCHAR(20)  NOT NULL DEFAULT 'pending'
                          CHECK (status IN ('pending','paid','overpaid','waived')),
  paid_amount           NUMERIC(12,2) NOT NULL DEFAULT 0,
  paid_at               TIMESTAMPTZ,
  notes                 VARCHAR(500),
  last_refreshed_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  created_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, business_id, tax_year, quarter)
);

CREATE INDEX IF NOT EXISTS idx_business_tax_est_user    ON business_tax_estimates(user_id);
CREATE INDEX IF NOT EXISTS idx_business_tax_est_due     ON business_tax_estimates(due_date)
  WHERE status = 'pending';

-- ── 5. Business revenue / growth goals ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS business_goals (
  id            BIGSERIAL PRIMARY KEY,
  user_id       UUID    NOT NULL REFERENCES users(id)      ON DELETE CASCADE,
  business_id   INT     NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  title         VARCHAR(120) NOT NULL,
  -- What metric this tracks
  goal_type     VARCHAR(30)  NOT NULL DEFAULT 'revenue'
                  CHECK (goal_type IN ('revenue','profit','jobs','clients','invoiced')),
  -- Period the target applies to
  period        VARCHAR(20)  NOT NULL DEFAULT 'monthly'
                  CHECK (period IN ('weekly','monthly','quarterly','yearly')),
  target_value  NUMERIC(12,2) NOT NULL CHECK (target_value > 0),
  -- current_value is auto-refreshed from analytics on GET; stored for history
  current_value NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Optional explicit date range (otherwise derived from `period` + now)
  period_start  DATE,
  period_end    DATE,
  is_completed  BOOLEAN NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_business_goals_business ON business_goals(business_id);
