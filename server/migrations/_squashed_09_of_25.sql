-- ── 3. Business invoices ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS business_invoices (
  id             BIGSERIAL PRIMARY KEY,
  user_id        UUID        NOT NULL REFERENCES users(id)       ON DELETE CASCADE,
  business_id    INT         NOT NULL REFERENCES businesses(id)  ON DELETE CASCADE,
  -- Human-readable number e.g. "INV-2026-0042"
  invoice_number VARCHAR(40) NOT NULL,
  -- Who is being billed
  client_name    VARCHAR(120) NOT NULL,
  client_email   VARCHAR(255),
  client_company VARCHAR(120),
  -- Lifecycle
  status         VARCHAR(20) NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft','sent','paid','overdue','cancelled','partial')),
  issue_date     DATE        NOT NULL DEFAULT CURRENT_DATE,
  due_date       DATE,
  -- Amounts — always stored in dollars
  subtotal       NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Tax percentage (0 = no sales tax on invoice; separate from income tax reserve)
  invoice_tax_rate NUMERIC(5,2) DEFAULT 0,
  tax_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
  total          NUMERIC(12,2) NOT NULL DEFAULT 0,
  amount_paid    NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Line items: [{description, quantity, unit_price, amount}]
  line_items     JSONB         NOT NULL DEFAULT '[]',
  -- Optional
  notes          VARCHAR(1000),
  -- Linked to an OxSteed job (optional)
  job_id         UUID REFERENCES jobs(id) ON DELETE SET NULL,
  -- Timestamps
  sent_at        TIMESTAMPTZ,
  paid_at        TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_business_invoices_user     ON business_invoices(user_id);
