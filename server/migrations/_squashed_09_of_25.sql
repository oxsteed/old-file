  -- current_value is auto-refreshed from analytics on GET; stored for history
  current_value NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Optional explicit date range (otherwise derived from `period` + now)
  period_start  DATE,
  period_end    DATE,
  is_completed  BOOLEAN NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_business_goals_business ON business_goals(business_id);

