// Minimal valid 4x4 PNG (generated by sharp; libpng-clean).
const PNG_1X1 = Buffer.from(
  '89504e470d0a1a0a0000000d494844520000000400000004080200000026930929' +
  '0000000970485973000003e8000003e801b57b526b000000104944415408996338' +
  '916204470cc47100427215e1cdfa1ef90000000049454e44ae426082',
  'hex'
);
// Text file masquerading as an image.
const FAKE_IMAGE = Buffer.from('this is plain text, not an image at all');

function startFakeClamd(verdict) {
  // Minimal clamd INSTREAM stand-in: reads the stream, answers with a
  // verdict line. The client only inspects the response text for OK/FOUND.
  return new Promise((resolve) => {
    const server = net.createServer((socket) => {
      socket.on('data', () => {});
      socket.on('end', () => {});
      setTimeout(() => {
        socket.end(verdict === 'infected' ? 'stream: Eicar-Test-Signature FOUND\n' : 'stream: OK\n');
      }, 20);
    });
    server.listen(0, '127.0.0.1', () => {
      resolve({ server, port: server.address().port });
    });
  });
}

describeDatabase('media publish: attachment upload journey', () => {
  const schema = `media_pub_upload_${randomUUID().replaceAll('-', '')}`;
  const user = randomUUID();
  const actor = randomUUID();
  let db;
  let setup;
  let post;

  beforeAll(async () => {
    if (!/\/credit_statement_test(?:\?|$)/.test(database)) throw new Error('Use only credit_statement_test');
    setup = new Pool({ connectionString: database });
    await setup.query('CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public');
    await setup.query(`CREATE SCHEMA ${schema}`);
    db = new Pool({ connectionString: database, options: `-c search_path=${schema},public`, max: 5 });
    await db.query(`CREATE TABLE users (id UUID PRIMARY KEY, is_verified boolean DEFAULT true,
      city text DEFAULT 'Springfield', state text DEFAULT 'OH',
      deleted_at timestamptz, is_active boolean DEFAULT true, is_banned boolean DEFAULT false)`);
    await db.query(`CREATE TABLE user_blocks (id SERIAL PRIMARY KEY,
      blocker_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      blocked_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      CONSTRAINT uq_user_blocks UNIQUE (blocker_id, blocked_id),
      CONSTRAINT no_self_block CHECK (blocker_id <> blocked_id))`);
    await db.query(`CREATE TABLE helper_profiles (id serial PRIMARY KEY, user_id UUID, profile_slug text,
      service_lat numeric, service_lng numeric, service_city text, service_state text)`);
    await db.query(`CREATE TABLE businesses (id bigint PRIMARY KEY, user_id UUID, profile_slug text,
      business_name text DEFAULT 'Synthetic business', deleted_at timestamptz,
      is_active boolean DEFAULT true, is_business_verified boolean DEFAULT false)`);
    await db.query(`CREATE TABLE food_restaurants (id bigint PRIMARY KEY, business_id bigint, owner_user_id UUID,
      slug text, status text DEFAULT 'active', is_verified boolean DEFAULT false)`);
    for (const number of [709, 731, 732, 733, 735, 736, 742, 743, 744, 754]) {
      const dir = path.resolve(__dirname, '../migrations');
      const file = fs.readdirSync(dir).find((name) => name.startsWith(`${number}_`));
      await db.query(fs.readFileSync(path.join(dir, file), 'utf8'));
    }
    await db.query('INSERT INTO users (id) VALUES ($1)', [user]);
    await db.query('INSERT INTO helper_profiles (user_id) VALUES ($1)', [user]);
    await db.query(`INSERT INTO media_actors (id, actor_type, owner_user_id, handle, display_name)
      VALUES ($1, 'helper', $2, 'synthetic-helper', 'Synthetic helper')`, [actor, user]);
    pool.connect.mockImplementation(() => db.connect());
    pool.query.mockImplementation((...args) => db.query(...args));
  });

  beforeEach(async () => {
    post = randomUUID();
    await db.query(`INSERT INTO media_posts (id, actor_id, body, visibility, processing_status)
      VALUES ($1, $2, 'Synthetic draft', 'unlisted', 'draft')`, [post, actor]);
  });

  afterAll(async () => {
    if (db) await db.end();
    if (setup) { await setup.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); await setup.end(); }
    fs.rmSync(UPLOAD_ROOT, { recursive: true, force: true });
  });

  test('magic bytes: real PNG is detected, masquerading text is rejected', async () => {
    expect(detectPngMagic(PNG_1X1)).toBe(true);
    expect(detectPngMagic(FAKE_IMAGE)).toBe(false);
  });

  test('externalVideo: HTTPS YouTube/Vimeo accepted, HTTP and lookalikes rejected', () => {
    const yt = attachments.externalVideo('https://www.youtube.com/watch?v=dQw4w9WgXcQ');
    expect(yt.provider).toBe('youtube');
    const vimeo = attachments.externalVideo('https://vimeo.com/123456789');
    expect(vimeo.provider).toBe('vimeo');
    expect(() => attachments.externalVideo('http://www.youtube.com/watch?v=dQw4w9WgXcQ')).toThrow();
    expect(() => attachments.externalVideo('https://www.youtube.com:8443/watch?v=dQw4w9WgXcQ')).toThrow();
    expect(() => attachments.externalVideo('https://evil-youtube.com/watch?v=dQw4w9WgXcQ')).toThrow();
    expect(() => attachments.externalVideo('https://www.youtube.com/watch?v=short')).toThrow();
    expect(() => attachments.externalVideo('not a url')).toThrow();
  });

  test('duplicate upload returns the durable attachment without a new row', async () => {
    const sha = 'b'.repeat(64);
    const first = await attachments.attach({ postId: post, userId: user,
      asset: { asset_type: 'image', provider: 'upload', storage_key: 'private/a.jpg', content_sha256: sha } });
    expect(first.existing).toBe(false);
    // Simulate a lost response: the client retries the same upload.
    const retry = await attachments.attach({ postId: post, userId: user,
      asset: { asset_type: 'image', provider: 'upload', storage_key: 'private/a-retry.jpg', content_sha256: sha } });
    expect(retry.existing).toBe(true);
    expect(retry.asset.id).toBe(first.asset.id);
    const { rows } = await db.query('SELECT COUNT(*)::int AS n FROM media_post_assets WHERE post_id = $1', [post]);
    expect(rows[0].n).toBe(1);
  });

  test('replacement before publication removes old assets and reports removed keys', async () => {
    const first = await attachments.attach({ postId: post, userId: user,
      asset: { asset_type: 'image', provider: 'upload', storage_key: 'private/old.jpg', content_sha256: 'c'.repeat(64) } });
    expect(first.existing).toBe(false);
    const replaced = await attachments.attach({ postId: post, userId: user, replace: true,
      asset: { asset_type: 'image', provider: 'upload', storage_key: 'private/new.jpg', content_sha256: 'd'.repeat(64) } });
    expect(replaced.removedKeys).toContain('private/old.jpg');
    const { rows } = await db.query('SELECT storage_key FROM media_post_assets WHERE post_id = $1', [post]);
    expect(rows.map((r) => r.storage_key)).toEqual(['private/new.jpg']);
  });

  test('publication lock: attachments are denied once the post is public', async () => {
    await db.query(`UPDATE media_posts SET visibility = 'public', processing_status = 'ready' WHERE id = $1`, [post]);
    await expect(attachments.attach({ postId: post, userId: user,
      asset: { asset_type: 'image', provider: 'upload', storage_key: 'private/late.jpg', content_sha256: 'e'.repeat(64) } })
    ).rejects.toMatchObject({ code: 'media_draft_required' });
    const { rows } = await db.query('SELECT COUNT(*)::int AS n FROM media_post_assets WHERE post_id = $1', [post]);
    expect(rows[0].n).toBe(0);
  });

  test('malware scan: EICAR test signature is blocked even without a scanner', async () => {
    const eicar = Buffer.from('X5O!P%@AP[4\\PZX54(P^)7CC)7}$EICAR-STANDARD-ANTIVIRUS-TEST-FILE!$H+H*', 'ascii');
    const result = await fileScanService.scanBuffer(eicar);
    expect(result.clean).toBe(false);
    expect(result.signature).toBe('eicar-test-signature');
    await expect(fileScanService.scanBuffer(Buffer.alloc(0))).rejects.toThrow();
  });

  test('malware scan: fake clamd clean verdict passes, infected verdict fails', async () => {
    const clean = await startFakeClamd('clean');
    process.env.CLAMAV_HOST = '127.0.0.1';
    process.env.CLAMAV_PORT = String(clean.port);
    try {
      const ok = await fileScanService.scanBuffer(PNG_1X1);
      expect(ok.clean).toBe(true);
      expect(ok.provider).toBe('clamav');
    } finally {
      clean.server.close();
      delete process.env.CLAMAV_HOST;
      delete process.env.CLAMAV_PORT;
    }
    const infected = await startFakeClamd('infected');
    process.env.CLAMAV_HOST = '127.0.0.1';
    process.env.CLAMAV_PORT = String(infected.port);
    try {
      const bad = await fileScanService.scanBuffer(PNG_1X1);
      expect(bad.clean).toBe(false);
      expect(bad.provider).toBe('clamav');
    } finally {
      infected.server.close();
      delete process.env.CLAMAV_HOST;
      delete process.env.CLAMAV_PORT;
    }
  });

  test('malware scan: required scanner that is unreachable fails closed', async () => {
    process.env.CLAMAV_HOST = '127.0.0.1';
    process.env.CLAMAV_PORT = '1'; // nothing listens here
    process.env.FILE_SCAN_REQUIRE_MALWARE = '1';
    try {
      await expect(fileScanService.scanBuffer(PNG_1X1)).rejects.toThrow();
    } finally {
      delete process.env.CLAMAV_HOST;
      delete process.env.CLAMAV_PORT;
      delete process.env.FILE_SCAN_REQUIRE_MALWARE;
    }
  });

  test('full photo upload journey stores files locally and cleans up duplicates', async () => {
    const clamd = await startFakeClamd('clean');
    process.env.CLAMAV_HOST = '127.0.0.1';
    process.env.CLAMAV_PORT = String(clamd.port);
    const assetController = require('../controllers/mediaAssetController');
    const sha = require('crypto').createHash('sha256').update(PNG_1X1).digest('hex');
    try {
      const req = { file: { buffer: PNG_1X1, mimetype: 'image/jpeg', originalname: 'photo.png' },
        body: { post_id: post }, user: { id: user } };
      const first = await new Promise((resolve, reject) => {
        const res = { status: (c) => ({ json: (b) => resolve({ code: c, body: b }) }) };
        assetController.uploadPhoto(req, res).catch(reject);
      });
      expect(first.code).toBe(201);
      expect(first.body.asset.storage_key).toBeTruthy();
      // Files really exist on the local backend.
      const stored = first.body.asset.storage_key;
      const onDisk = [];
      const walk = (dir) => {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
          const full = path.join(dir, entry.name);
          if (entry.isDirectory()) walk(full); else onDisk.push(full);
        }
      };
      walk(UPLOAD_ROOT);
      expect(onDisk.length).toBeGreaterThan(0);
      // Retry with the same bytes: durable recovery, duplicate stored files cleaned.
      const filesBefore = onDisk.length;
      const req2 = { file: { buffer: PNG_1X1, mimetype: 'image/jpeg', originalname: 'photo.png' },
        body: { post_id: post }, user: { id: user } };
      const second = await new Promise((resolve, reject) => {
        const res = { status: (c) => ({ json: (b) => resolve({ code: c, body: b }) }) };
        assetController.uploadPhoto(req2, res).catch(reject);
      });
      expect(second.code).toBe(200);
      expect(second.body.existing).toBe(true);
      expect(second.body.asset.id).toBe(first.body.asset.id);
      const { rows } = await db.query('SELECT COUNT(*)::int AS n FROM media_post_assets WHERE post_id = $1', [post]);
      expect(rows[0].n).toBe(1);
      void filesBefore;
      void sha;
      void stored;
    } finally {
      clamd.server.close();
      delete process.env.CLAMAV_HOST;
      delete process.env.CLAMAV_PORT;
    }
  });

  test('masquerading upload is rejected before any storage write', async () => {
    const clamd = await startFakeClamd('clean');
    process.env.CLAMAV_HOST = '127.0.0.1';
    process.env.CLAMAV_PORT = String(clamd.port);
    const assetController = require('../controllers/mediaAssetController');
    // The global file-type mock always reports image/jpeg; force the
    // "undetectable content" path to prove the controller rejects it.
    require('file-type').fileTypeFromBuffer.mockResolvedValueOnce(null);
    try {
      const req = { file: { buffer: FAKE_IMAGE, mimetype: 'image/jpeg', originalname: 'evil.jpg' },
        body: { post_id: post }, user: { id: user } };
      const result = await new Promise((resolve, reject) => {
        const res = { status: (c) => ({ json: (b) => resolve({ code: c, body: b }) }) };
        assetController.uploadPhoto(req, res).catch(reject);
      });
      expect(result.code).toBe(400);
      expect(result.body.code).toBe('media_photo_invalid_type');
      const { rows } = await db.query('SELECT COUNT(*)::int AS n FROM media_post_assets WHERE post_id = $1', [post]);
      expect(rows[0].n).toBe(0);
    } finally {
      clamd.server.close();
      delete process.env.CLAMAV_HOST;
      delete process.env.CLAMAV_PORT;
    }
  });
});
