#!/usr/bin/env python3
"""Groups 5-6 generator. Run from the repo root after editing:
  - server/utils/businessTeamNotificationTemplates.js (notification types)
  - docs/persona-roadmap/group5-6-copy.json ({"a.b": [en, es, fr, ht, ar]} or {"a.b": {"en":..}})
It rewrites (idempotently):
  1. the "Groups 5-6" literal block in server/utils/notificationTypeCatalog.js
  2. the variable-site entry in server/__tests__/notificationsPrefsToggles.db.test.js
  3. the trailing "bizG56" block in all 20 client/src/locales/*.json
     (locales without their own text get English, i18next fallback text)."""
import json, glob, os, re, sys
root = sys.argv[1] if len(sys.argv) > 1 else '.'
tpl = open(os.path.join(root, 'server/utils/businessTeamNotificationTemplates.js'), encoding='utf-8').read()
types = re.findall(r'^  ([a-z0-9_]+): \{', tpl, re.M)
# 1. catalog
p = os.path.join(root, 'server/utils/notificationTypeCatalog.js'); s = open(p, encoding='utf-8').read()
start, end = '  // >>> Groups 5-6 (generated by docs/persona-roadmap/tools/group56-sync.py)\n', '  // <<< Groups 5-6\n'
block = start + ''.join(f"  {{ type: '{t}', group: 'work' }},\n" for t in types) + end
if start in s:
    s = s[:s.index(start)] + block + s[s.index(end) + len(end):]
else:
    i = s.index('\n];\n'); s = s[:i + 1] + block + s[i + 1:]
open(p, 'w', encoding='utf-8').write(s)
# 2. toggles test variable site
p = os.path.join(root, 'server/__tests__/notificationsPrefsToggles.db.test.js'); s = open(p, encoding='utf-8').read()
line = "        { file: 'services/businessOwner/common.js', name: 'type', expansions: [" + ', '.join(f"'{t}'" for t in types) + "] },\n"
pat = re.compile(r"        \{ file: 'services/businessOwner/common\.js'.*\n")
if pat.search(s): s = pat.sub(lambda m: line, s)
else:
    anchor = '      const VARIABLE_SITES = [\n'; s = s.replace(anchor, anchor + "        // Groups 5-6: notify() in services/businessOwner/common.js.\n" + line, 1)
open(p, 'w', encoding='utf-8').write(s)
# 3. locales
copy_path = os.path.join(root, 'docs/persona-roadmap/group5-6-copy.json')
copy = json.load(open(copy_path, encoding='utf-8')) if os.path.exists(copy_path) else {}
MARK = '  "bizG56": {'
for path in sorted(glob.glob(os.path.join(root, 'client/src/locales/*.json'))):
    lang = os.path.basename(path)[:-5]
    s = open(path, encoding='utf-8').read()
    i = s.find('\n' + MARK)
    if i >= 0:
        head = s[:i].rstrip(); assert head.endswith(','), path; head = head[:-1]
    else:
        head = s.rstrip(); assert head.endswith('}'), path; head = head[:-1].rstrip()
    tree = {}
    for dotted, texts in copy.items():
        if isinstance(texts, list): texts = dict(zip(['en', 'es', 'fr', 'ht', 'ar'], texts))
        node = tree; parts = dotted.split('.')
        for q in parts[:-1]: node = node.setdefault(q, {})
        node[parts[-1]] = texts.get(lang) or texts['en']
    out = head + ',\n  "bizG56": ' + json.dumps(tree, ensure_ascii=False, indent=2).replace('\n', '\n  ') + '\n}\n'
    json.loads(out); open(path, 'w', encoding='utf-8').write(out)
print('types', len(types), 'copy', len(copy))
