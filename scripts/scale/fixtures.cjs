'use strict';

/**
 * Deterministic fixture generator for V2-P1-05.
 *
 * The audit asks for "realistic six-million-user and 3,500-employee
 * fixtures with geographic and workload skew". Generating six million real
 * rows is an operator-run step against a scratch database, so this tool
 * generates:
 *   1. scale-model.json - the full 6M/3,500 model with per-region and
 *      per-role counts plus derived peak load (the source of truth for the
 *      model; no rows needed).
 *   2. users.jsonl / staff.jsonl - deterministic synthetic samples.
 *   3. seed.sql - CREATE TABLE + INSERTs for scratch tables named
 *      scale_fixture_* (clearly synthetic, test-only; never production).
 *
 * Output is deterministic per --seed: the same seed always yields
 * byte-identical files, so fixture drift is detectable in CI.
 */

const fs = require('fs');
const path = require('path');
const { SCALE_MODEL, deriveLoad } = require('./scaleModel.cjs');

const LOCALES = ['en', 'es', 'fr', 'ht', 'ar'];
const DEVICES = ['ios', 'android', 'web'];

function mulberry32(seed) {
  let a = seed >>> 0;
  return function rand() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pickWeighted(rand, entries) {
  let r = rand();
  for (const entry of entries) {
    r -= entry.share;
    if (r <= 0) return entry;
  }
  return entries[entries.length - 1];
}

function pick(rand, list) {
  return list[Math.floor(rand() * list.length)];
}

function syntheticId(rand, prefix) {
  const hex = () => Math.floor(rand() * 0xffffffffffff).toString(16).padStart(12, '0');
  return `${prefix}_${hex()}`;
}

function generateUsers(rand, count) {
  const users = [];
  const customerPersonas = SCALE_MODEL.personas.filter((p) => p.id !== 'staff');
  const total = customerPersonas.reduce((acc, p) => acc + p.share, 0);
  const normalized = customerPersonas.map((p) => ({ ...p, share: p.share / total }));
  for (let i = 0; i < count; i += 1) {
    const region = pickWeighted(rand, SCALE_MODEL.regions);
    const persona = pickWeighted(rand, normalized);
    users.push({
      synthetic_id: syntheticId(rand, 'u'),
      region: region.id,
      persona: persona.id,
      locale: pick(rand, LOCALES),
      device: pick(rand, DEVICES),
      created_days_ago: Math.floor(rand() * 900),
    });
  }
  return users;
}

function generateStaff(rand, count) {
  const staff = [];
  for (let i = 0; i < count; i += 1) {
    const region = pickWeighted(rand, SCALE_MODEL.regions);
    const role = pickWeighted(rand, SCALE_MODEL.staff.roles);
    staff.push({
      synthetic_id: syntheticId(rand, 's'),
      region: region.id,
      role: role.id,
      locale: pick(rand, LOCALES),
    });
  }
  return staff;
}

function sqlEscape(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function buildSeedSql(users, staff) {
  const lines = [
    '-- Synthetic scale fixtures for V2-P1-05. TEST-ONLY scratch tables.',
    '-- Generated by scripts/scale/fixtures.cjs. Never apply to production.',
    '',
    'CREATE TABLE IF NOT EXISTS scale_fixture_users (',
    '  synthetic_id TEXT PRIMARY KEY,',
    '  region TEXT NOT NULL,',
    '  persona TEXT NOT NULL,',
    '  locale TEXT NOT NULL,',
    '  device TEXT NOT NULL,',
    '  created_days_ago INTEGER NOT NULL',
    ');',
    '',
    'CREATE TABLE IF NOT EXISTS scale_fixture_staff (',
    '  synthetic_id TEXT PRIMARY KEY,',
    '  region TEXT NOT NULL,',
    '  role TEXT NOT NULL,',
    '  locale TEXT NOT NULL',
    ');',
    '',
  ];
  for (const u of users) {
    lines.push(
      `INSERT INTO scale_fixture_users (synthetic_id, region, persona, locale, device, created_days_ago) VALUES (${sqlEscape(u.synthetic_id)}, ${sqlEscape(u.region)}, ${sqlEscape(u.persona)}, ${sqlEscape(u.locale)}, ${sqlEscape(u.device)}, ${u.created_days_ago}) ON CONFLICT (synthetic_id) DO NOTHING;`,
    );
  }
  for (const s of staff) {
    lines.push(
      `INSERT INTO scale_fixture_staff (synthetic_id, region, role, locale) VALUES (${sqlEscape(s.synthetic_id)}, ${sqlEscape(s.region)}, ${sqlEscape(s.role)}, ${sqlEscape(s.locale)}) ON CONFLICT (synthetic_id) DO NOTHING;`,
    );
  }
  return `${lines.join('\n')}\n`;
}

function buildModelJson() {
  const load = deriveLoad();
  return {
    generatedAt: new Date().toISOString(),
    note: 'Full 6M-user / 3,500-staff model. Counts are modeled, not materialized rows.',
    totalUsers: SCALE_MODEL.totalUsers,
    totalStaff: SCALE_MODEL.totalStaff,
    regions: load.perRegion,
    personas: SCALE_MODEL.personas,
    staffRoles: SCALE_MODEL.staff.roles.map((role) => ({
      ...role,
      count: Math.round(SCALE_MODEL.totalStaff * role.share),
    })),
    derivedPeak: {
      peakConcurrentUsers: load.peakConcurrentUsers,
      peakConcurrentStaff: load.peakConcurrentStaff,
      peakConcurrentSessions: load.peakConcurrentSessions,
      peakRequestsPerSecond: load.peakRequestsPerSecond,
      trafficMixRps: load.trafficMixRps,
    },
  };
}

function generateFixtures({ seed = 42, sampleUsers = 5000, sampleStaff = 350, outDir = 'scale-fixtures' } = {}) {
  const rand = mulberry32(seed);
  const users = generateUsers(rand, sampleUsers);
  const staff = generateStaff(rand, sampleStaff);
  fs.mkdirSync(outDir, { recursive: true });
  const written = {};
  written.model = path.join(outDir, 'scale-model.json');
  fs.writeFileSync(written.model, `${JSON.stringify(buildModelJson(), null, 2)}\n`);
  written.users = path.join(outDir, 'users.jsonl');
  fs.writeFileSync(written.users, users.map((u) => JSON.stringify(u)).join('\n') + '\n');
  written.staff = path.join(outDir, 'staff.jsonl');
  fs.writeFileSync(written.staff, staff.map((s) => JSON.stringify(s)).join('\n') + '\n');
  written.sql = path.join(outDir, 'seed.sql');
  fs.writeFileSync(written.sql, buildSeedSql(users, staff));
  return { seed, sampleUsers: users.length, sampleStaff: staff.length, files: written };
}

function parseArgs(argv) {
  const args = { seed: 42, sampleUsers: 5000, sampleStaff: 350, outDir: 'scale-fixtures', help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--seed' && argv[i + 1]) args.seed = Number(argv[++i]);
    else if (a === '--sample-users' && argv[i + 1]) args.sampleUsers = Number(argv[++i]);
    else if (a === '--sample-staff' && argv[i + 1]) args.sampleStaff = Number(argv[++i]);
    else if (a === '--out' && argv[i + 1]) args.outDir = argv[++i];
    else if (a === '--help' || a === '-h') args.help = true;
  }
  return args;
}

if (require.main === module) {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log('Usage: node scripts/scale/fixtures.cjs [--seed N] [--sample-users N] [--sample-staff N] [--out DIR]');
    console.log('Generates deterministic synthetic scale fixtures (samples only, never 6M rows).');
    process.exit(0);
  }
  const result = generateFixtures({ seed: args.seed, sampleUsers: args.sampleUsers, sampleStaff: args.sampleStaff, outDir: args.outDir });
  console.log(`seed=${result.seed} users=${result.sampleUsers} staff=${result.sampleStaff}`);
  for (const file of Object.values(result.files)) console.log(`wrote ${file}`);
}

module.exports = { generateFixtures, generateUsers, generateStaff, buildSeedSql, buildModelJson, mulberry32 };
